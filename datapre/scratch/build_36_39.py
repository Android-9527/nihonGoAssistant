def w(ch, kana, kanji, chinese):
    return {"chapter": ch, "kana": kana, "kanji": kanji, "chinese": chinese}

def s(ch, sentence, chinese):
    return {"chapter": ch, "sentence": sentence, "chinese": chinese}

def mul(ch, items):
    return {"chapter": ch, "sentences": [s(ch, *it) for it in items]}

def grammar(ch, template, explanation, sentences=None, muls=None):
    return {"chapter": ch, "template": template, "explanation": explanation,
            "sentences": sentences or [], "mul_sentences": muls or []}

def dialogue(ch, title, pairs):
    return {"chapter": ch, "title": title,
            "sentences": [s(ch, sp, zh) for sp, zh in pairs]}

def essay(ch, title, pairs):
    return {"chapter": ch, "title": title,
            "sentences": [s(ch, jp, zh) for jp, zh in pairs]}

